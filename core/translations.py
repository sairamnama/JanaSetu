def get_translation(key: str, lang: Optional[str] = None, default: Optional[str] = None) -> str:
    """Retrieve translated text by key for the given language (defaults to 'en')."""
    if not lang or lang not in TRANSLATIONS:
        lang = DEFAULT_LANGUAGE
    dict_for_lang = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    return dict_for_lang.get(key, default if default is not None else TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))

